    # === MÉTHODES DE VALIDATION D'ORIGINE ===
    
    def _validate_lead_origin(self, lead_id: int) -> bool:
        """
        Valider qu'un lead appartient bien à cette campagne
        
        Vérifications:
        1. lead.campaign == self.campaign
        2. lead.source_activity appartient à cette campagne
        3. lead.contact fait partie des targets de cette campagne
        """
        try:
            from apps.leads.models import Lead
            
            lead = Lead.objects.select_related(
                'campaign', 'source_activity__campaign_info__campaign', 'contact', 'account'
            ).get(id=lead_id)
            
            # Vérification directe: lead.campaign
            if hasattr(lead, 'campaign') and lead.campaign == self.campaign:
                return True
            
            # Vérification via source_activity
            if hasattr(lead, 'source_activity') and lead.source_activity:
                source_activity = lead.source_activity
                if (hasattr(source_activity, 'campaign_info') and 
                    source_activity.campaign_info and 
                    source_activity.campaign_info.campaign == self.campaign):
                    return True
            
            # Vérification via contact/account dans campaign targets
            if hasattr(lead, 'contact') and lead.contact:
                contact_in_campaign = self.campaign.targets.filter(
                    models.Q(contact=lead.contact) | 
                    models.Q(account=lead.contact.account)
                ).exists()
                if contact_in_campaign:
                    return True
            
            # Vérification via account dans campaign targets
            if hasattr(lead, 'account') and lead.account:
                account_in_campaign = self.campaign.targets.filter(account=lead.account).exists()
                if account_in_campaign:
                    return True
            
            return False
            
        except Lead.DoesNotExist:
            return False
        except Exception:
            return False
    
    def _validate_meeting_origin(self, meeting_id: int) -> bool:
        """
        Valider qu'un meeting appartient bien à cette campagne
        
        Vérifications:
        1. activity.campaign_info.campaign == self.campaign
        2. activity fait partie d'une séquence de cette campagne
        """
        try:
            from apps.activities.models import Activity
            
            meeting = Activity.objects.select_related(
                'campaign_info__campaign'
            ).get(id=meeting_id, activity_type=Activity.ActivityType.MEETING)
            
            # Vérification directe via campaign_info
            if (hasattr(meeting, 'campaign_info') and 
                meeting.campaign_info and 
                meeting.campaign_info.campaign == self.campaign):
                return True
            
            # Vérification via account dans campaign targets
            if hasattr(meeting, 'account') and meeting.account:
                account_in_campaign = self.campaign.targets.filter(account=meeting.account).exists()
                if account_in_campaign:
                    return True
            
            return False
            
        except Activity.DoesNotExist:
            return False
        except Exception:
            return False
    
    def _validate_opportunity_origin(self, opportunity_id: int) -> bool:
        """
        Valider qu'une opportunity appartient bien à cette campagne
        
        Vérifications multi-degrés:
        1. opportunity.source.source_campaign == self.campaign
        2. opportunity provient d'un lead de cette campagne
        3. opportunity.account fait partie des targets
        4. opportunity créée depuis une activity de cette campagne
        """
        try:
            from apps.opportunities.models import Opportunity
            
            # ✅ CORRIGÉ: 'source' au lieu de 'sources' (OneToOneField)
            opportunity = Opportunity.objects.select_related(
                'account', 'contact', 'source'  
            ).get(id=opportunity_id)
            
            # ✅ CORRIGÉ: Accès direct à .source au lieu de boucle .sources.all()
            if hasattr(opportunity, 'source') and opportunity.source:
                source = opportunity.source
                
                # Vérification directe via OpportunitySource
                if (hasattr(source, 'source_campaign') and 
                    source.source_campaign == self.campaign):
                    return True
                
                # Vérification via lead source
                if (hasattr(source, 'source_lead') and 
                    source.source_lead and
                    self._validate_lead_origin(source.source_lead.id)):
                    return True
            
            # Vérification via account dans campaign targets
            if hasattr(opportunity, 'account') and opportunity.account:
                account_in_campaign = self.campaign.targets.filter(
                    models.Q(account=opportunity.account) |
                    models.Q(target_opportunity=opportunity)
                ).exists()
                if account_in_campaign:
                    return True
            
            # Vérification via contact dans campaign targets
            if hasattr(opportunity, 'contact') and opportunity.contact:
                contact_in_campaign = self.campaign.targets.filter(
                    models.Q(contact=opportunity.contact) |
                    models.Q(account=opportunity.contact.account)
                ).exists()
                if contact_in_campaign:
                    return True
            
            return False
            
        except Opportunity.DoesNotExist:
            return False
        except Exception as e:
            return False
    
    def _validate_deal_origin(self, deal_id: int) -> bool:
        """
        Valider qu'un deal (opportunity fermée) appartient bien à cette campagne
        Utilise la même logique que _validate_opportunity_origin
        """
        return self._validate_opportunity_origin(deal_id)
    
    # === MÉTHODES DE TRACKING SÉCURISÉES ===
    
    def track_lead(self, lead_id: int) -> bool:
        """
        Track a new lead, avoiding duplicates and validating origin
        
        Args:
            lead_id: ID of the lead to track
            
        Returns:
            bool: True if lead was added, False if already tracked or invalid
            
        Raises:
            StandardizedValidationError: If origin validation fails
        """
        try:
            # Éviter les doublons
            if lead_id in self.tracked_lead_ids:
                return False
            
            # Valider l'origine
            if not self._validate_lead_origin(lead_id):
                raise StandardizedValidationError(
                    CampaignErrorMessages.CAMPAIGN_ACTIVITY_ORPHANED.format(
                        activity=f"Lead {lead_id} does not belong to campaign {self.campaign.id}"
                    )
                )
            
            # Ajouter l'ID et incrémenter
            self.tracked_lead_ids.append(lead_id)
            self.leads_created_count += 1
            self.save(update_fields=['tracked_lead_ids', 'leads_created_count'])
            
            return True
            
        except StandardizedValidationError:
            # Re-raise validation errors
            raise
        except Exception as e:
            raise StandardizedValidationError(
                CoreErrorMessages.UNEXPECTED_ERROR.format(detail=f"Lead tracking failed: {str(e)}")
            )
    
    def track_meeting(self, meeting_id: int) -> bool:
        """Track a new meeting, avoiding duplicates and validating origin"""
        try:
            if meeting_id in self.tracked_meeting_ids:
                return False
            
            # Valider l'origine
            if not self._validate_meeting_origin(meeting_id):
                raise StandardizedValidationError(
                    CampaignErrorMessages.CAMPAIGN_ACTIVITY_ORPHANED.format(
                        activity=f"Meeting {meeting_id} does not belong to campaign {self.campaign.id}"
                    )
                )
            
            self.tracked_meeting_ids.append(meeting_id)
            self.meetings_secured_count += 1
            self.save(update_fields=['tracked_meeting_ids', 'meetings_secured_count'])
            
            return True
            
        except StandardizedValidationError:
            raise
        except Exception as e:
            raise StandardizedValidationError(
                CoreErrorMessages.UNEXPECTED_ERROR.format(detail=f"Meeting tracking failed: {str(e)}")
            )
    
    def track_opportunity(self, opportunity_id: int, pipeline_value: Decimal = None) -> bool:
        """Track a new opportunity with optional pipeline value and origin validation"""
        try:
            if opportunity_id in self.tracked_opportunity_ids:
                return False

            # Valider l'origine
            if not self._validate_opportunity_origin(opportunity_id):
                raise StandardizedValidationError(
                    CampaignErrorMessages.CAMPAIGN_ACTIVITY_ORPHANED.format(
                        activity=f"Opportunity {opportunity_id} does not belong to campaign {self.campaign.id}"
                    )
                )

            self.tracked_opportunity_ids.append(opportunity_id)
            self.opportunities_created_count += 1
            
            if pipeline_value and pipeline_value > 0:
                self.pipeline_value_created += pipeline_value

            self.save(update_fields=[
                'tracked_opportunity_ids', 
                'opportunities_created_count',
                'pipeline_value_created'
            ])
            return True
            
        except StandardizedValidationError:
            raise
        except Exception as e:
            print(f"Error tracking opportunity2: {str(e)}")
            raise StandardizedValidationError(
                CoreErrorMessages.UNEXPECTED_ERROR.format(detail=f"Opportunity tracking failed: {str(e)}")
            )
    
    def track_deal_closed(self, opportunity_id: int, revenue: Decimal = None) -> bool:
        """Track a deal closure with revenue and origin validation"""
        try:
            if opportunity_id in self.tracked_deal_ids:
                return False
            
            # Valider l'origine
            if not self._validate_deal_origin(opportunity_id):
                raise StandardizedValidationError(
                    CampaignErrorMessages.CAMPAIGN_ACTIVITY_ORPHANED.format(
                        activity=f"Deal {opportunity_id} does not belong to campaign {self.campaign.id}"
                    )
                )
            
            self.tracked_deal_ids.append(opportunity_id)
            self.deals_closed_count += 1
            
            if revenue and revenue > 0:
                self.revenue_generated += revenue
            
            self.save(update_fields=[
                'tracked_deal_ids',
                'deals_closed_count', 
                'revenue_generated'
            ])
            
            return True
            
        except StandardizedValidationError:
            raise
        except Exception as e:
            raise StandardizedValidationError(
                CoreErrorMessages.UNEXPECTED_ERROR.format(detail=f"Deal tracking failed: {str(e)}")
            )
    
    # === MÉTHODES DE VÉRIFICATION D'INTÉGRITÉ AVANCÉES ===
    
    def get_integrity_report(self) -> Dict:
        """
        Vérifier l'intégrité des IDs trackés avec validation d'origine
        
        Returns:
            Dict: Rapport complet avec validation d'existence ET d'origine
        """
        report = {
            'timestamp': self.last_updated.isoformat(),
            'campaign_id': self.campaign.id,
            'campaign_name': self.campaign.name,
            'leads': self._check_ids_integrity_with_origin('leads', self.tracked_lead_ids),
            'meetings': self._check_ids_integrity_with_origin('meetings', self.tracked_meeting_ids), 
            'opportunities': self._check_ids_integrity_with_origin('opportunities', self.tracked_opportunity_ids),
            'deals': self._check_ids_integrity_with_origin('deals', self.tracked_deal_ids),
        }
        
        # Calculer score d'intégrité global
        total_ids = sum(len(section['tracked_ids']) for section in report.values() if isinstance(section, dict))
        valid_ids = sum(len(section['valid_ids']) for section in report.values() if isinstance(section, dict))
        
        report['integrity_score'] = (valid_ids / total_ids * 100) if total_ids > 0 else 100
        report['needs_cleanup'] = report['integrity_score'] < 100
        
        # Détection des IDs orphelins (existent mais n'appartiennent pas à la campagne)
        orphaned_total = sum(len(section['orphaned_ids']) for section in report.values() if isinstance(section, dict))
        report['has_orphaned_objects'] = orphaned_total > 0
        report['orphaned_objects_count'] = orphaned_total
        
        return report
    
    def _check_ids_integrity_with_origin(self, object_type: str, tracked_ids: List[int]) -> Dict:
        """Helper pour vérifier l'intégrité ET l'origine d'un type d'objet"""
        try:
            existing_ids = set()
            valid_origin_ids = set()
            
            if object_type == 'leads':
                from apps.leads.models import Lead
                all_existing_ids = set(Lead.objects.filter(id__in=tracked_ids).values_list('id', flat=True))
                existing_ids = all_existing_ids
                
                # Valider l'origine pour chaque lead existant
                for lead_id in all_existing_ids:
                    if self._validate_lead_origin(lead_id):
                        valid_origin_ids.add(lead_id)
                        
            elif object_type == 'meetings':
                from apps.activities.models import Activity
                all_existing_ids = set(Activity.objects.filter(
                    id__in=tracked_ids,
                    activity_type=Activity.ActivityType.MEETING
                ).values_list('id', flat=True))
                existing_ids = all_existing_ids
                
                for meeting_id in all_existing_ids:
                    if self._validate_meeting_origin(meeting_id):
                        valid_origin_ids.add(meeting_id)
                        
            elif object_type in ['opportunities', 'deals']:
                from apps.opportunities.models import Opportunity
                all_existing_ids = set(Opportunity.objects.filter(id__in=tracked_ids).values_list('id', flat=True))
                existing_ids = all_existing_ids
                
                for opp_id in all_existing_ids:
                    if self._validate_opportunity_origin(opp_id):
                        valid_origin_ids.add(opp_id)
            
            tracked_set = set(tracked_ids)
            deleted_ids = tracked_set - existing_ids  # IDs qui n'existent plus
            orphaned_ids = existing_ids - valid_origin_ids  # IDs qui existent mais n'appartiennent plus à la campagne
            
            return {
                'tracked_ids': tracked_ids,
                'existing_ids': list(existing_ids),
                'valid_ids': list(valid_origin_ids),
                'deleted_ids': list(deleted_ids),  # Objets supprimés
                'orphaned_ids': list(orphaned_ids),  # Objets qui n'appartiennent plus à la campagne
                'integrity_percentage': (len(valid_origin_ids) / len(tracked_ids) * 100) if tracked_ids else 100,
                'needs_cleanup': len(deleted_ids) > 0 or len(orphaned_ids) > 0
            }
            
        except Exception as e:
            return {
                'tracked_ids': tracked_ids,
                'existing_ids': [],
                'valid_ids': [],
                'deleted_ids': tracked_ids,
                'orphaned_ids': [],
                'integrity_percentage': 0,
                'needs_cleanup': True,
                'error': f'Failed to check integrity: {str(e)}'
            }